#!/usr/bin/env python3
"""Round 8 'question bombardment' runner.

Merges every qa/eval/bombard-*.json generated by the independent question
generators, de-duplicates by normalized query, replays each through the
resolver's own scorer (tools/router_match.rank), and reports hit-rate overall,
per dimension (cat) and per language (zh / en / ms / mixed), plus all misses and
(none)-case false positives.

Advisory: prints a report and exits 0; it never fails the build.
"""
from __future__ import annotations
import glob, json, re, sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from router_match import rank  # noqa: E402

MS_HINTS = ("yang", "nak", "tak", "saya", "awak", "boleh", "lah", "lah", "macam",
            "mana", "kena", "dah", "tidak", "mahu", "jangan", "risau", "sia")


def lang_of(q: str) -> str:
    cjk = bool(re.search(r"[\u4e00-\u9fff]", q))
    ql = q.lower()
    ms = any(re.search(r"(?<![a-z])" + w + r"(?![a-z])", ql) for w in MS_HINTS)
    if cjk and (ms or re.search(r"[a-z]{2,}", ql)):
        return "mixed" if ms else "zh+en"
    if cjk:
        return "zh"
    if ms:
        return "ms"
    return "en"


def load_cases() -> list[dict]:
    cases, seen = [], set()
    for f in sorted(glob.glob(str(ROOT / "qa/eval/bombard-*.json"))):
        try:
            data = json.loads(Path(f).read_text(encoding="utf-8"))
        except Exception as e:
            print(f"  [warn] skip {Path(f).name}: {e}")
            continue
        for c in data.get("cases", []):
            q = (c.get("q") or "").strip()
            if not q:
                continue
            key = re.sub(r"\s+", "", q.lower())
            if key in seen:
                continue
            seen.add(key)
            cases.append({"q": q, "expect": c.get("expect", "(none)"),
                          "cat": c.get("cat", "?"), "src": Path(f).stem})
    return cases


def pct(a, b):
    return f"{100*a//b}% ({a}/{b})" if b else "n/a"


def main() -> int:
    router = json.loads((ROOT / "router.json").read_text(encoding="utf-8"))
    cases = load_cases()
    if not cases:
        print("run_bombard: no cases found (run the generators first)")
        return 0

    cat_hit, cat_tot = defaultdict(int), defaultdict(int)
    lang_hit, lang_tot = defaultdict(int), defaultdict(int)
    misses, fps = [], []
    for c in cases:
        ranked = rank(router, c["q"])
        got = ranked[0]["id"] if ranked else None
        got_lang = ranked[0]["score"] if ranked else 0
        lang = lang_of(c["q"])
        lang_tot[lang] += 1
        if c["expect"] == "(none)":
            if got is not None:
                fps.append((c["q"], got, got_lang, c["cat"]))
            else:
                lang_hit[lang] += 1
            continue
        cat_tot[c["cat"]] += 1
        if got == c["expect"]:
            cat_hit[c["cat"]] += 1
            lang_hit[lang] += 1
        else:
            misses.append((c["q"], c["expect"], got, got_lang, c["cat"], lang))

    scored = sum(cat_tot.values())
    print(f"== Round 8 bombardment ==")
    print(f"cases: {len(cases)}  (scored: {scored}, (none): {len(cases)-scored})")
    print(f"overall hit: {pct(sum(cat_hit.values()), scored)}")
    print("\n-- by dimension (cat) --")
    for cat in sorted(cat_tot, key=lambda k: (cat_hit[k]/cat_tot[k], k)):
        print(f"  {cat:16} {pct(cat_hit[cat], cat_tot[cat])}")
    print("\n-- by language --")
    for lang in sorted(lang_tot):
        print(f"  {lang:8} {pct(lang_hit[lang], lang_tot[lang])}")
    if misses:
        print(f"\n-- misses ({len(misses)}) --")
        for q, exp, got, sc, cat, lang in misses:
            print(f"  [{cat}/{lang}] {q!r}\n        want {exp}, got {got} (score {sc})")
    if fps:
        print(f"\n-- (none) false positives ({len(fps)}) --")
        for q, got, sc, cat in fps:
            print(f"  [{cat}] {q!r} -> {got} (score {sc})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
